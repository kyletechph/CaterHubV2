-- CaterHub security patch. Run once in the Supabase SQL editor (safe to run again).
-- Fixes: (1) any customer could change the status of ANY inquiry, (2) customers could pick their own
-- inquiry reference, (3) owners could publish an incomplete profile, (4) an owner could wipe customers'
-- inquiries by deleting their profile, (5) unlimited status-message length.

-- 1) set_inquiry_status: NULL-safe authorization.
--    Before: for a user without a caterer profile, is_owner was NULL, so "if not (is_owner or is_customer)"
--    evaluated to NULL and the check was skipped. Now both flags are always true/false.
create or replace function public.set_inquiry_status(p_id bigint, p_status inquiry_status, p_message text default null)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  inq inquiries%rowtype;
  is_owner boolean;
  is_customer boolean;
  notify_user uuid;
  biz text;
  who text;
begin
  select * into inq from inquiries where inquiry_id = p_id;
  if not found then
    raise exception 'Inquiry not found.';
  end if;

  is_owner    := coalesce(inq.caterer_id = my_caterer_id(), false);
  is_customer := coalesce(inq.customer_id in (select customer_id from customers where user_id = auth.uid()), false);

  if not (is_owner or is_customer) then
    raise exception 'Not allowed.';
  end if;

  -- customers may only cancel their own Pending inquiry
  if not is_owner and not (inq.status = 'Pending' and p_status = 'Cancelled') then
    raise exception 'Customers can only cancel a Pending inquiry.';
  end if;

  if length(coalesce(p_message, '')) > 1000 then
    raise exception 'Message is too long (max 1000 characters).';
  end if;

  if p_status in ('Unavailable', 'Cancelled') and coalesce(trim(p_message), '') = '' then
    raise exception 'A reply is required for Unavailable or Cancelled.';
  end if;

  update inquiries set status = p_status where inquiry_id = p_id;

  insert into inquiry_status_history (inquiry_id, previous_status, status, message, changed_by)
  values (p_id, inq.status, p_status, nullif(trim(p_message), ''), auth.uid());

  select business_name into biz from caterer_profiles where caterer_id = inq.caterer_id;

  if is_owner then
    select user_id into notify_user from customers where customer_id = inq.customer_id;
    who := coalesce(biz, 'The caterer');
  else
    select user_id into notify_user from caterer_profiles where caterer_id = inq.caterer_id;
    select name into who from customers where customer_id = inq.customer_id;
    who := coalesce(who, 'The customer');
  end if;

  if notify_user is not null and notify_user is distinct from auth.uid() then
    insert into notifications (user_id, message, type)
    values (notify_user,
            who || ' updated ' || inq.ref || ' to "' || p_status || '"' || coalesce(': ' || nullif(trim(p_message), ''), '.'),
            'inquiry');
  end if;
end $$;

revoke execute on function public.set_inquiry_status(bigint, inquiry_status, text) from public, anon;
grant  execute on function public.set_inquiry_status(bigint, inquiry_status, text) to authenticated;

-- 2) The inquiry reference is always generated by the database, never chosen by the client.
alter table inquiries alter column ref drop default;
create or replace function public.force_inquiry_ref() returns trigger
language plpgsql as $$
begin
  new.ref := 'INQ-' || lpad(nextval('inquiry_ref_seq')::text, 6, '0');
  return new;
end $$;
drop trigger if exists force_inquiry_ref on inquiries;
create trigger force_inquiry_ref before insert on inquiries
  for each row execute function public.force_inquiry_ref();

-- 3) A profile can only be Published when its required details are filled in (same rules as the checklist
--    in the app; the business description is optional, as in the app; service areas are saved after the profile row, so they stay checked in the app only).
create or replace function public.enforce_publish_rules() returns trigger
language plpgsql as $$
begin
  if new.status = 'Published' and (
       coalesce(trim(new.business_name), '') = ''
    or coalesce(trim(new.contact_number), '') = ''
    or coalesce(array_length(new.event_types, 1), 0) = 0
    or coalesce(new.max_guests, 0) <= 0
    or coalesce(new.min_guests, 0) > new.max_guests
  ) then
    raise exception 'Complete the publishing checklist before publishing.';
  end if;
  return new;
end $$;
drop trigger if exists enforce_publish_rules on caterer_profiles;
create trigger enforce_publish_rules before insert or update on caterer_profiles
  for each row execute function public.enforce_publish_rules();

-- 4) Owners can no longer delete their profile through the API (it cascades and erases every customer's
--    inquiry history). The app uses "Deactivate profile" instead, which keeps the records.
drop policy if exists profiles_delete on caterer_profiles;

notify pgrst, 'reload schema';
